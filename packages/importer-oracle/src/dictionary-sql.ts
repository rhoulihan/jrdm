export const TABLES_SQL = `
  SELECT TABLE_NAME
  FROM ALL_TABLES
  WHERE OWNER = :owner
  ORDER BY TABLE_NAME
`;

export const COLUMNS_SQL = `
  SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE,
         CHAR_LENGTH, NULLABLE, DATA_DEFAULT, COLUMN_ID
  FROM ALL_TAB_COLUMNS
  WHERE OWNER = :owner
  ORDER BY TABLE_NAME, COLUMN_ID
`;

export const PK_UK_SQL = `
  SELECT c.CONSTRAINT_NAME, c.CONSTRAINT_TYPE, cc.TABLE_NAME, cc.COLUMN_NAME, cc.POSITION
  FROM ALL_CONSTRAINTS c
  JOIN ALL_CONS_COLUMNS cc ON cc.OWNER = c.OWNER AND cc.CONSTRAINT_NAME = c.CONSTRAINT_NAME
  WHERE c.OWNER = :owner AND c.CONSTRAINT_TYPE IN ('P','U')
  ORDER BY cc.TABLE_NAME, c.CONSTRAINT_NAME, cc.POSITION
`;

export const FK_SQL = `
  SELECT c.CONSTRAINT_NAME, cc.TABLE_NAME, cc.COLUMN_NAME, cc.POSITION,
         rc.TABLE_NAME AS REF_TABLE, rcc.COLUMN_NAME AS REF_COLUMN, rcc.POSITION AS REF_POSITION,
         c.R_OWNER AS REF_OWNER
  FROM ALL_CONSTRAINTS c
  JOIN ALL_CONS_COLUMNS cc ON cc.OWNER = c.OWNER AND cc.CONSTRAINT_NAME = c.CONSTRAINT_NAME
  JOIN ALL_CONSTRAINTS rc ON rc.OWNER = c.R_OWNER AND rc.CONSTRAINT_NAME = c.R_CONSTRAINT_NAME
  JOIN ALL_CONS_COLUMNS rcc ON rcc.OWNER = rc.OWNER AND rcc.CONSTRAINT_NAME = rc.CONSTRAINT_NAME
                           AND rcc.POSITION = cc.POSITION
  WHERE c.OWNER = :owner AND c.CONSTRAINT_TYPE = 'R'
  ORDER BY cc.TABLE_NAME, c.CONSTRAINT_NAME, cc.POSITION
`;
